// Evaluation harness. Writes EVAL.md with measured numbers only.
//   npm run eval            → rule engine + image pipeline (offline, no keys needed)
//   npm run eval -- --ai    → also the Gemini judge and Gemini vision (needs GEMINI_API_KEY and GEMINI_MODEL in .env.local)
// The AI part uses every seed rule and fact as the retrieved context, so it needs no database.
import { config } from "dotenv";
import { execSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { applyFixes } from "../lib/checks/apply";
import { runDeterministicChecks } from "../lib/checks/deterministic";
import { imageTextFindings, runImageChecks } from "../lib/checks/image-checks";
import type { CheckContext, DraftFinding } from "../lib/checks/types";
import { SEED_FACTS, SEED_PALETTE, SEED_RULES, SEED_TERMS } from "../lib/demo/seed-data";
import { SAMPLES } from "../lib/demo/samples";
import { contrastRatio, hexToRgb } from "../lib/images/color";
import { dominantColours, measureTextBlocks } from "../lib/images/pixels";
import { AI_CASES, RULE_CASES } from "./eval-cases";

config({ path: ".env.local" });

const ctx: CheckContext = {
  rules: SEED_RULES.map((r) => ({ ...r, params: r.params ?? {}, active: true })),
  terms: SEED_TERMS,
  facts: SEED_FACTS,
  today: new Date().toLocaleDateString("en-CA", { timeZone: "Asia/Kolkata" }),
};

const key = (f: DraftFinding) => (f.factCode ? `${f.ruleCode}/${f.factCode}` : `${f.ruleCode}`);
const matches = (expected: string, f: DraftFinding) => (expected.includes("/") ? key(f) === expected : f.ruleCode === expected);
const pct = (n: number, d: number) => (d ? `${((100 * n) / d).toFixed(0)}%` : "n/a");
const ms = (n: number) => `${n.toFixed(n < 10 ? 2 : 0)} ms`;

function median(xs: number[]) {
  const s = [...xs].sort((a, b) => a - b);
  return s.length ? s[Math.floor((s.length - 1) / 2)] : 0;
}

async function main() {
  const wantAi = process.argv.includes("--ai");
  const lines: string[] = [];
  const out = (s = "") => lines.push(s);
  let commit = "unknown";
  try {
    commit = execSync("git rev-parse --short HEAD").toString().trim();
  } catch {
    /* not a git checkout */
  }

  out("# Evaluation");
  out();
  out(`Generated by \`scripts/eval.ts\` on ${new Date().toISOString()} at commit \`${commit}\`. Every number below was measured by that run. Re-run with \`npm run eval\` (add \`-- --ai\` for the Gemini part).`);
  out();

  // ---------------- 1. Rule engine on the labelled set ----------------
  let tp = 0;
  let fp = 0;
  let fn = 0;
  let cleanCases = 0;
  let cleanWithFp = 0;
  const times: number[] = [];
  const rows: string[] = [];
  const misses: string[] = [];
  for (const c of RULE_CASES) {
    const t0 = performance.now();
    const found = runDeterministicChecks({ text: c.text, channel: c.channel }, ctx);
    times.push(performance.now() - t0);
    const hit = c.expected.filter((e) => found.some((f) => matches(e, f)));
    const extra = found.filter((f) => !c.expected.some((e) => matches(e, f)));
    tp += hit.length;
    fn += c.expected.length - hit.length;
    // Several findings with the same unexpected key count as one false positive.
    const extraKeys = [...new Set(extra.map(key))];
    fp += extraKeys.length;
    if (c.expected.length === 0) {
      cleanCases++;
      if (extraKeys.length) cleanWithFp++;
    }
    const ok = hit.length === c.expected.length && extraKeys.length === 0;
    rows.push(`| ${c.id} | ${c.expected.join(", ") || "(clean)"} | ${[...new Set(found.map(key))].join(", ") || "none"} | ${ok ? "✅" : "❌"} |`);
    if (!ok) misses.push(`- **${c.id}**: expected ${c.expected.join(", ") || "nothing"}, got ${[...new Set(found.map(key))].join(", ") || "nothing"}. Text: “${c.text}”`);
  }
  const passed = rows.filter((r) => r.endsWith("✅ |")).length;

  out("## 1. Rule engine (deterministic, no LLM)");
  out();
  out(`${RULE_CASES.length} hand-labelled cases in \`scripts/eval-cases.ts\`, written separately from the demo samples. ${cleanCases} are compliant copy that should produce no findings. A finding counts as correct when its rule (and fact, where the label names one) matches the label.`);
  out();
  out("| Metric | Result |");
  out("|---|---|");
  out(`| Cases fully correct | ${passed} / ${RULE_CASES.length} (${pct(passed, RULE_CASES.length)}) |`);
  out(`| Recall (expected issues found) | ${tp} / ${tp + fn} (${pct(tp, tp + fn)}) |`);
  out(`| Precision (findings that were expected) | ${tp} / ${tp + fp} (${pct(tp, tp + fp)}) |`);
  out(`| Compliant cases with a false positive | ${cleanWithFp} / ${cleanCases} |`);
  out(`| Median time per check | ${ms(median(times))} |`);
  out();
  out("<details><summary>Per-case results</summary>");
  out();
  out("| Case | Expected | Found | OK |");
  out("|---|---|---|---|");
  rows.forEach((r) => out(r));
  out();
  out("</details>");
  out();
  if (misses.length) {
    out("**Misses and false positives (reported as-is, not tuned away):**");
    out();
    misses.forEach((m) => out(m));
    out();
  }

  // ---------------- 2. Fix effectiveness on the demo samples ----------------
  out("## 2. Do the suggested fixes work?");
  out();
  out("For each text sample: apply every suggested rule fix, then check the result again.");
  out();
  out("| Sample | Findings | Fixes applied | Findings after re-check |");
  out("|---|---|---|---|");
  for (const s of SAMPLES) {
    const f1 = runDeterministicChecks({ text: s.text, channel: s.channel }, ctx);
    const fixed = applyFixes(s.text, f1.map((f) => ({ spanStart: f.spanStart, spanEnd: f.spanEnd, fix: f.suggestedFix })));
    const f2 = runDeterministicChecks({ text: fixed.text, channel: s.channel }, ctx);
    out(`| ${s.label} | ${f1.length} | ${fixed.applied} | ${f2.length}${f2.length ? ` (${f2.map(key).join(", ")})` : ""} |`);
  }
  out();
  out("The image sample's issues are in the picture, not the text, so they are measured in section 3.");
  out();

  // ---------------- 3. Image pipeline ----------------
  out("## 3. Image pipeline (sample 4, offline part)");
  out();
  const buf = readFileSync(path.join(process.cwd(), "public", "samples", "festive-ad.png"));
  const t0 = performance.now();
  const colours = await dominantColours(buf);
  // Ground-truth boxes for the generated image (we drew it, so the positions are known).
  const blocks = await measureTextBlocks(buf, [
    { text: "Festive Glow Sale", box: [200, 50, 300, 950], text_color: "#000000", background_color: "#FFFFFF" },
    { text: "Lumina Vitamin C Serum", box: [400, 100, 480, 900], text_color: "#000000", background_color: "#FFFFFF" },
    { text: "now just ₹399", box: [530, 230, 610, 770], text_color: "#000000", background_color: "#FFFFFF" },
    { text: "Shop now", box: [715, 370, 785, 630], text_color: "#000000", background_color: "#FFFFFF" },
  ]);
  const pixelMs = performance.now() - t0;
  // True colours used to draw the image (scripts/make-sample-image.ts).
  const truth: Record<string, [string, string]> = {
    "Festive Glow Sale": ["#FFD23F", "#F28C28"],
    "Lumina Vitamin C Serum": ["#FFE9A8", "#F28C28"],
    "now just ₹399": ["#FFD23F", "#F28C28"],
    "Shop now": ["#FFFFFF", "#0E7C7B"],
  };
  out("Text colours and contrast measured from the pixels, compared with the colours the image was drawn with:");
  out();
  out("| Text | Measured | Measured ratio | True ratio | Verdict (4.5:1) |");
  out("|---|---|---|---|---|");
  let verdictAgree = 0;
  for (const b of blocks) {
    const r = contrastRatio(hexToRgb(b.textHex), hexToRgb(b.backgroundHex));
    const [tf, tb] = truth[b.text];
    const rt = contrastRatio(hexToRgb(tf), hexToRgb(tb));
    if (r >= 4.5 === rt >= 4.5) verdictAgree++;
    out(`| ${b.text} | ${b.textHex} on ${b.backgroundHex} | ${r.toFixed(2)}:1 | ${rt.toFixed(2)}:1 | ${r >= 4.5 ? "pass" : "fail"} (${r >= 4.5 === rt >= 4.5 ? "agrees" : "DISAGREES"} with truth) |`);
  }
  out();
  out(`Pass/fail agreement with the true colours: ${verdictAgree} / ${blocks.length}. Dominant colours: ${colours
    .filter((c) => c.share >= 0.01)
    .map((c) => `${c.hex} (${Math.round(c.share * 100)}%)`)
    .join(", ")}. Pixel analysis time: ${ms(pixelMs)}.`);
  out();
  const imgFindings = [
    ...runImageChecks({ altText: null, description: null, colours, blocks }, ctx, SEED_PALETTE),
    ...imageTextFindings(Object.keys(truth).join("\n"), "ad", ctx),
  ];
  const expectedImg = ["A-01", "A-02", "V-01", "C-03/F-12"];
  const foundImg = expectedImg.filter((e) => imgFindings.some((f) => matches(e, f)));
  out(`Planted issues detected (given the image text): ${foundImg.length} / ${expectedImg.length} (${foundImg.join(", ")}). All findings: ${[...new Set(imgFindings.map(key))].join(", ")}.`);
  out();
  out("In the app the text boxes come from Gemini vision rather than the known positions used here. Section 4 measures that step.");
  out();

  // ---------------- 4. AI (optional) ----------------
  out("## 4. AI judge and vision (Gemini)");
  out();
  const haveKey = !!process.env.GEMINI_API_KEY && !!process.env.GEMINI_MODEL;
  if (!wantAi || !haveKey) {
    out(
      !wantAi
        ? "Not run in this evaluation. Run `npm run eval -- --ai` with `GEMINI_API_KEY` and `GEMINI_MODEL` set to measure it. No AI numbers are claimed until then."
        : "Skipped: `GEMINI_API_KEY` / `GEMINI_MODEL` are not set. No AI numbers are claimed.",
    );
    out();
  } else {
    const { runAiStage } = await import("../lib/checks/ai-stage");
    const { readImage } = await import("../lib/images/analyze");
    const allRetriever = { retrieve: async () => ({ rules: ctx.rules, facts: ctx.facts, trace: [] }) };
    out(`Model: \`${process.env.GEMINI_MODEL}\`, temperature 0. All seed rules and facts are given as the retrieved context.`);
    out();
    out("| Case | Expected | AI findings (after validation) | Hit | Time |");
    out("|---|---|---|---|---|");
    let hits = 0;
    let expectedCount = 0;
    let cleanFp = 0;
    const agg = { received: 0, kept: 0, droppedBadQuote: 0, downgradedCitation: 0, downgradedConfidence: 0, droppedDuplicate: 0 };
    const aiTimes: number[] = [];
    let failures = 0;
    for (const c of AI_CASES) {
      const det = runDeterministicChecks({ text: c.text, channel: c.channel }, ctx);
      const t = performance.now();
      const res = await runAiStage({
        orgId: "eval",
        orgName: "Lumina Skin",
        channel: c.channel,
        goal: c.goal,
        audience: c.audience,
        cta: c.cta,
        text: c.text,
        redactedContent: c.text,
        extractedText: null,
        ctx,
        deterministic: det,
        retriever: allRetriever,
      });
      const elapsed = performance.now() - t;
      aiTimes.push(elapsed);
      if (res.status !== "completed") {
        failures++;
        out(`| ${c.id} | ${c.expectAny.join(" or ") || "(clean)"} | ${res.status}: ${res.status === "failed" ? res.error : res.reason} | ❌ | ${ms(elapsed)} |`);
        continue;
      }
      for (const k of Object.keys(agg) as (keyof typeof agg)[]) agg[k] += res.stats[k];
      const desc = res.findings.map((f) => `${f.ruleCode ?? f.category}${f.factCode ? "/" + f.factCode : ""} (${f.label})`).join(", ") || "none";
      let hit: boolean;
      if (c.expectAny.length === 0) {
        hit = res.findings.length === 0;
        if (!hit) cleanFp++;
      } else {
        expectedCount++;
        hit = res.findings.some((f) => c.expectAny.includes(f.ruleCode ?? "") || c.expectAny.includes(f.category));
        if (hit) hits++;
      }
      out(`| ${c.id} | ${c.expectAny.join(" or ") || "(clean)"} | ${desc} | ${hit ? "✅" : "❌"} | ${ms(elapsed)} |`);
    }
    out();
    out("| Metric | Result |");
    out("|---|---|");
    out(`| AI-only issues caught | ${hits} / ${expectedCount} |`);
    out(`| Clean cases with an AI finding | ${cleanFp} / ${AI_CASES.filter((c) => !c.expectAny.length).length} |`);
    out(`| Calls that failed or timed out | ${failures} / ${AI_CASES.length} |`);
    out(`| Raw AI findings → kept after validation | ${agg.received} → ${agg.kept} |`);
    out(`| Dropped: quote not in the text | ${agg.droppedBadQuote} |`);
    out(`| Dropped: duplicate of a rule finding | ${agg.droppedDuplicate} |`);
    out(`| Downgraded to needs-human-verification (citation / confidence) | ${agg.downgradedCitation} / ${agg.downgradedConfidence} |`);
    out(`| Median judge latency | ${ms(median(aiTimes))} |`);
    out();

    // Vision on the sample image
    try {
      const t = performance.now();
      const v = await readImage({ mimeType: "image/png", buffer: buf });
      const vMs = performance.now() - t;
      const want = Object.keys(truth);
      const norm = (s: string) => s.replace(/\s+/g, " ").trim().toLowerCase();
      const got = want.filter((w) => norm(v.text).includes(norm(w)));
      const measured = await measureTextBlocks(buf, v.text_blocks);
      const fails = measured.filter((b) => contrastRatio(hexToRgb(b.textHex), hexToRgb(b.backgroundHex)) < 4.5).map((b) => b.text);
      const vf = imageTextFindings(v.text, "ad", ctx);
      out("**Vision on sample 4:**");
      out();
      out(`- Text lines read exactly: ${got.length} / ${want.length}${got.length < want.length ? ` (missed: ${want.filter((w) => !got.includes(w)).join(", ")})` : ""}`);
      out(`- Text blocks returned: ${v.text_blocks.length}. Measured from pixels: ${measured.filter((b) => b.method === "measured").length}. Blocks failing contrast: ${fails.join(", ") || "none"}`);
      out(`- Wrong price caught from the image text (C-03/F-12): ${vf.some((f) => matches("C-03/F-12", f)) ? "yes" : "no"}`);
      out(`- Vision latency: ${ms(vMs)}`);
      out();
    } catch (err) {
      out(`**Vision on sample 4:** failed: ${err instanceof Error ? err.message : String(err)}`);
      out();
    }
  }

  out("## Limits of this evaluation");
  out();
  out("- The labelled set is small (written for this MVP) and was written by the builder, so it measures whether each rule works as specified, not real-world accuracy.");
  out("- The rule engine is pattern-based: paraphrases outside its patterns are left to the AI judge, which is why the AI section exists.");
  out("- AI results vary between model versions. The model name is recorded on every check row and in the audit log.");

  writeFileSync(path.join(process.cwd(), "EVAL.md"), lines.join("\n") + "\n");
  console.log(lines.join("\n"));
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
